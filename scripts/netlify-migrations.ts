/**
 * Prepare netlify/database/migrations — Netlify applies these to the hosted Postgres on every deploy.
 *
 *   npx tsx scripts/netlify-migrations.ts
 *
 * 1. Copies each Drizzle migration (drizzle/*.sql) with a timestamp prefix taken from Drizzle's journal.
 * 2. Creates a one-time "seed_content" migration (menu, styles, gallery, settings, hours, first artist)
 *    if it doesn't exist yet. It's never regenerated: Netlify rejects edited migrations.
 *
 * Run after `npm run db:generate` and commit the result.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ART_STYLES, BUSINESS_HOURS, CATEGORIES, FIRST_STAFF, SERVICES, SETTINGS, galleryRows } from "../src/db/seed-content";

const OUT = path.resolve("netlify/database/migrations");
mkdirSync(OUT, { recursive: true });

const stamp = (ms: number) => new Date(ms).toISOString().replace(/[-:T]/g, "").slice(0, 14);

// ── 1. Schema migrations from Drizzle ──
const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8")) as { entries: { tag: string; when: number }[] };
for (const e of journal.entries) {
  const name = `${stamp(e.when)}_${e.tag.replace(/^\d+_/, "")}.sql`;
  const sql = readFileSync(path.join("drizzle", `${e.tag}.sql`), "utf8");
  const target = path.join(OUT, name);
  if (existsSync(target)) {
    if (readFileSync(target, "utf8") !== sql) throw new Error(`${name} differs from drizzle/${e.tag}.sql — never edit an applied migration; generate a new one.`);
    continue;
  }
  writeFileSync(target, sql);
  console.log(`+ ${name}`);
}

// ── 2. One-time starter content ──
const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const insert = (table: string, rows: Record<string, unknown>[]) =>
  rows.length
    ? `INSERT INTO "${table}" (${Object.keys(rows[0]).map((c) => `"${c}"`).join(", ")}) VALUES\n` +
      rows.map((r) => `  (${Object.values(r).map(lit).join(", ")})`).join(",\n") +
      `\nON CONFLICT DO NOTHING;\n`
    : "";

async function seedMigration() {
  if (readdirSync(OUT).some((f) => f.endsWith("_seed_content.sql"))) return;
  const last = Math.max(...journal.entries.map((e) => e.when));
  const { media, items, covers } = await galleryRows();
  const sql = [
    "-- Starter content for BLUSH (generated by scripts/netlify-migrations.ts — do not edit; add a new migration instead).",
    insert("settings", SETTINGS.map((s) => ({ key: s.key, value: s.value }))),
    insert("business_hours", BUSINESS_HOURS.map((h) => ({ weekday: h.weekday, is_closed: h.isClosed, open_time: h.openTime, close_time: h.closeTime }))),
    insert("staff", [{ id: FIRST_STAFF.id, display_name: FIRST_STAFF.displayName }]),
    insert("service_categories", CATEGORIES.map((c) => ({ id: c.id, name: c.name, slug: c.slug, sort_order: c.sortOrder }))),
    insert("services", SERVICES.map((s) => ({ id: s.id, category_id: s.categoryId, name: s.name, slug: s.slug, summary: s.summary, price_type: s.priceType, base_price: s.basePrice, duration_min: s.durationMin, buffer_min: s.bufferMin, booking_mode: s.bookingMode, sort_order: s.sortOrder }))),
    insert("art_styles", ART_STYLES.map((s) => ({ id: s.id, name: s.name, slug: s.slug, sort_order: s.sortOrder }))),
    insert("media", media.map((m) => ({ id: m.id, kind: m.kind, path: m.path, mime: m.mime, width: m.width, height: m.height, bytes: m.bytes }))),
    insert("gallery_items", items.map((g) => ({ id: g.id, media_id: g.mediaId, caption: g.caption, art_style_id: g.artStyleId, is_featured: g.isFeatured, is_published: g.isPublished, client_consent: g.clientConsent, sort_order: g.sortOrder }))),
    ...covers.map((c) => `UPDATE "art_styles" SET "cover_media_id" = ${lit(c.mediaId)} WHERE "id" = ${lit(c.styleId)} AND "cover_media_id" IS NULL;\n`),
  ].join("\n");
  const name = `${stamp(last + 1000)}_seed_content.sql`;
  writeFileSync(path.join(OUT, name), sql);
  console.log(`+ ${name}`);
}

seedMigration().then(() => console.log("✔ netlify/database/migrations up to date"));
